import test from 'node:test';
import assert from 'node:assert/strict';
import { setup, draw } from './fixtures.ts';
import { Scene } from '../src/scene.ts';
await test('portable Wasm actions preserve rejected drafts and cancel accepted Undo once', async () => {
  const { engine: e, work } = await setup();
  e.begin(0xfedcba9876543210n, 2);
  e.append(0xfedcba9876543210n, [{ x: 20, y: 20, time: 0, id: 1n }]);
  assert.throws(() => e.action('undo'));
  assert.equal(e.state().interaction, 1);
  assert.throws(() => e.scale(NaN));
  assert.equal(e.state().interaction, 1);
  e.cancel();
  draw(e);
  e.begin(7n, 2);
  e.append(7n, [{ x: 30, y: 30, time: 0, id: 1n }]);
  e.action('undo');
  assert.equal(e.state().interaction, 0);
  assert.equal(e.state().count, 0n);
  e.action('redo');
  assert.equal(e.state().count, 1n);
  e.action('next');
  assert.equal(e.state().tool, 'select');
  e.scale(2);
  e.action('delete');
  assert.equal(e.state().count, 0n);
  await work.shutdown();
});
await test('portable Wasm leased scenes reuse unchanged geometry and suppress preview original', async () => {
  const { engine: e, work } = await setup();
  draw(e);
  const scene = new Scene(e),
    viewport = [0, 0, 500, 500, 32];
  const first = scene.update(viewport);
  assert.equal(scene.update(viewport), first);
  assert.equal(first.strokes.length, 1);
  e.action('next');
  e.beginTransform();
  e.transform(2, 20, 20);
  const preview = scene.update(viewport);
  assert.equal(preview.strokes.length, 1);
  assert.equal(preview.strokes[0].scale, 2);
  e.commitTransform();
  e.action('undo');
  assert.equal(scene.update(viewport).strokes[0].scale, 1);
  e.action('redo');
  assert.equal(scene.update(viewport).strokes[0].scale, 2);
  e.action('delete');
  assert.equal(scene.update(viewport).strokes.length, 0);
  assert.equal(scene.frame.geometry.size, 0);
  scene.dispose();
  await work.shutdown();
});
